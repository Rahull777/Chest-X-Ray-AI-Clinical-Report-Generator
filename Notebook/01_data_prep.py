def ensemble_predict(loaders, trained_models, weights):
    all_probs  = {name: [] for name in trained_models}
    all_labels = []
    collected  = False

    for name, (model, _, _) in trained_models.items():
        model.eval()
        with torch.no_grad():
            for images, labels in loaders:
                images = images.to(DEVICE)
                logits = model(images)
