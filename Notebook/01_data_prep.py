# ---- Helper: ensemble inference from TRAINED_MODELS
def run_ensemble_inference(img_path: str):
    img = Image.open(img_path).convert("RGB")
    x = infer_transform(img).unsqueeze(0).to(DEVICE)

    model_probs = []

    with torch.no_grad():
        for name, model_info in TRAINED_MODELS.items(): # Ensure correct variable name

            model = model_info[0] if isinstance(model_info, tuple) else model_info
            model.eval()

            logits = model(x)
            probs = F.softmax(logits, dim=1).squeeze(0).cpu().numpy()
            model_probs.append(probs)

    avg_probs = np.mean(model_probs, axis=0)
    pred_idx = int(np.argmax(avg_probs))
    pred_label = CLASS_LIST[pred_idx]
    confidence = float(avg_probs[pred_idx] * 100.0)

    class_probs = {
        CLASS_LIST[i]: float(avg_probs[i] * 100.0)
        for i in range(len(CLASS_LIST))
    }

    return pred_label, confidence, class_probs


# ---- Helper: hybrid retrieval
def run_hybrid_rag(query: str, k: int = 4):
    results = hybrid_search(query, k=k, alpha=0.6)

    docs = []
    scores = []
    for item in results:
        # hybrid_search returns tuples like: (doc, hybrid_score, sem_score, bm25_score)
        doc = item[0]
        hybrid_score = item[1]
        docs.append(doc)
        scores.append(hybrid_score)

    return docs, scores


# ---- Main pipeline ------------------------------------------
def generate_clinical_report(img_path: str) -> dict:
    try:
        # Step 1: Ensemble prediction
        diagnosis, confidence, class_probs = run_ensemble_inference(img_path)

        # Step 2: Hybrid RAG Retrieval using the diagnosis
        rag_docs, rag_scores = run_hybrid_rag(diagnosis, k=4) # Updated to get scores

        context = "\n\n".join([doc.page_content for doc in rag_docs])
        sources = ", ".join(sorted(list(set([f"{d.metadata['source']} p.{d.metadata['page_num']}" for d in rag_docs]))))

        # Step 3: LLM Report Generation
        report_text = report_chain.invoke({
            "diagnosis"  : diagnosis,
            "confidence" : confidence,
            "class_probs": class_probs,
            "context"    : context,
            "sources"    : sources,
        })

        return {
            "image_path" : img_path,
            "diagnosis"  : diagnosis,
            "confidence" : confidence,
            "class_probs": class_probs,
            "report"     : report_text,
            "sources"    : sources,
            "rag_docs"   : rag_docs,
            "rag_scores" : rag_scores # Included rag_scores
        }

    except Exception as e:
        return {
            "image_path" : img_path,
            "diagnosis"  : None,
            "confidence" : None,
            "class_probs": {},
            "report"     : None,
            "sources"    : [],
            "rag_docs"   : [],
            "rag_scores" : [],
            "error"      : str(e)
        }

